//! Regenerates the OneBot mapper's QQ face names from a SnowLuma `sys-face-catalog.json`.
use anyhow::{Context, Result};
use serde_json::Value;
use std::{collections::BTreeMap, fmt::Write, path::Path};

const TABLE: &str = "plugins/onebot/src/faces.rs";

/// Numbered faces only, each named by its description without the leading `/`; the first
/// pack that names an ID wins.
pub(crate) fn generate(catalog: &Path) -> Result<()> {
    let bytes = std::fs::read(catalog).with_context(|| format!("reading {}", catalog.display()))?;
    let catalog: Value = serde_json::from_slice(&bytes).context("parsing the face catalog")?;
    let mut names = BTreeMap::new();
    let packs = catalog["packs"].as_array().context("catalog packs")?;
    for emoji in packs
        .iter()
        .flat_map(|pack| pack["emojis"].as_array().into_iter().flatten())
    {
        let id = emoji["qSid"].as_str().and_then(|id| id.parse::<u32>().ok());
        if let (Some(id), Some(name)) = (id, emoji["qDes"].as_str()) {
            let name = name.strip_prefix('/').unwrap_or(name);
            names.entry(id).or_insert_with(|| name.to_owned());
        }
    }
    let mut table = String::from(
        "//! Pinned QQ system-face names, from Tencent via SnowLuma's face catalog.\n\
         // Generated by `cargo xtask faces <sys-face-catalog.json>`; do not edit.\n\n\
         pub(super) static NAMES: &[(u32, &str)] = &[\n",
    );
    for (id, name) in names {
        writeln!(table, "    ({id}, {name:?}),")?;
    }
    table.push_str("];\n");
    std::fs::write(TABLE, table).with_context(|| format!("writing {TABLE}"))
}
