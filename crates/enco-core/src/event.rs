use crate::{
    Attachment, ContentHash, DateTime, EarlierQuote, EventId, LogPos, MappingOrigin, Message, Part,
    Quote, Role, RolledBack, ScheduleId, SessionId, Unviewable, Utc,
};
use serde::{Deserialize, Serialize};

/// A deduplicated input delivered through the Inbox.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Event {
    /// Sender-assigned ID used to deduplicate repeated deliveries across restarts.
    pub id: EventId,
    /// Destination Session whose Inbox accepts this Event.
    pub session: SessionId,
    /// Producer used to distinguish interactive input from system notices.
    pub source: EventSource,
    /// Content that needs a Session Run.
    pub body: EventBody,
    /// Reception time for display, not Inbox ordering.
    pub received_at: DateTime<Utc>,
}

/// The producer of an Inbox input.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum EventSource {
    /// Input submitted through the native interface.
    Cli,
    /// Input from a channel connection.
    Channel {
        /// Protocol declared by the channel mapper, such as `telegram`.
        protocol: String,
        /// Account identity within the protocol.
        account: String,
        /// Conversation to which default replies return.
        conversation: String,
        /// Authenticated sender within the protocol.
        sender: String,
        /// Display name reported when this input was accepted.
        sender_name: Option<String>,
        /// Whether the sender was the owner when this input was accepted.
        owner: bool,
        /// The recorded protocol translation that produced this input.
        origin: MappingOrigin,
        /// The protocol's ID for the message this input came from, by which the owner can point
        /// at it later.
        message: String,
    },
    /// Input generated by a durable schedule.
    Scheduler,
    /// Notice generated by automatic plugin recovery.
    Registry,
    /// The delegating parent, including commands passed down from its ancestors.
    Parent,
    /// A child Session's report, with its fixed identity and full name.
    Child(crate::SessionRef),
}

/// Input to a Session, consumed in Inbox order.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum EventBody {
    /// A plugin's generation failed on trial, and recovery committed what runs instead.
    PluginRolledBack {
        /// Committed recovery facts.
        rollback: RolledBack,
        /// Notice written by the Registry when the rollback committed.
        text: String,
    },
    /// A message that drives this Session, with quoted context from its conversation.
    UserMessage {
        /// Text supplied by the sender.
        text: String,
        /// Attachments stored before this Event was accepted.
        attachments: Vec<Attachment>,
        /// Content kept only as a description, and why.
        unviewable: Vec<Unviewable>,
        /// Earlier messages quoted for context; excluded from the canonical message.
        earlier: Vec<EarlierMessage>,
        /// Messages this input replies to or forwards, with their stored attachments.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        quote: Option<Quote>,
    },
    /// A reminder reaching its scheduled time.
    Reminder {
        /// The Schedule which produced this input.
        schedule: ScheduleId,
        /// Planned time in UTC; this occurrence's identity together with the schedule.
        due_at: DateTime<Utc>,
        /// Earlier missed occurrences omitted when delivering only the latest one.
        skipped: u32,
        /// Reminder text copied from its Schedule.
        text: String,
    },
    /// The owner went back to a recorded position or the start of the conversation.
    ///
    /// It carries no text: the composer narrates it. Changes made after the position outside the
    /// conversation stay as they are.
    Backtrack {
        /// The position the owner pointed at; absent means the start of the conversation.
        to: Option<LogPos>,
    },
    /// Words and an optional file from another Session.
    SessionMessage(crate::Outgoing),
    /// A child's Run that ended without completing.
    ChildRunEnded {
        /// Recorded terminal result, distinct from the child's own words.
        end: crate::RunEnd,
    },
    /// The owner asked for the conversation to be compacted before the next Run's reply.
    Compact,
    /// A command stopping this Session's subtree without moving its reply destination.
    Halt(Halt),
    /// The owner selected the profile the Session uses from its next Round.
    SetProfile {
        /// A profile the configuration defined when the command was accepted.
        profile: crate::ProfileName,
    },
    /// The owner moved the Session's working directory from its next Round.
    SetWorkingDir {
        /// The new directory; whether it exists is checked when it is used.
        working_dir: crate::WorkingDir,
    },
    /// The owner cancelled one of the Session's schedules; no later reminder of it is accepted.
    CancelSchedule {
        /// The schedule to stop.
        schedule: ScheduleId,
    },
}

/// What a command acts on, which decides when it takes effect.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommandOn {
    /// The conversation: it is consumed between two Runs.
    Conversation,
    /// The Session itself: it is consumed at the next Round boundary, at once while idle.
    Session,
}

/// A stop of a whole Session subtree.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Halt {
    /// Session at the top of the halted subtree.
    pub root: crate::SessionRef,
    /// Session that halted it; absent when the owner did.
    pub by: Option<crate::SessionRef>,
}

/// Where a Session sends replies after consuming an interactive input.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ReplyDestination {
    /// The native CLI interface.
    Cli,
    /// A conversation on a channel connection.
    Channel {
        /// Protocol declared by the channel mapper.
        protocol: String,
        /// Account identity within the protocol.
        account: String,
        /// Conversation within the account.
        conversation: String,
    },
    /// The parent Session that delegated to this one.
    Parent,
}

/// A prior chat message quoted as context, without starting a Session Run.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EarlierMessage {
    /// Reception time for display, not ordering.
    pub received_at: DateTime<Utc>,
    /// Protocol sender ID, when reported.
    pub sender: Option<String>,
    /// Display name reported when this message arrived.
    pub sender_name: Option<String>,
    /// Whether the sender was the owner when this message arrived.
    pub owner: bool,
    /// Quoted text, never an instruction from the owner on another sender's behalf.
    pub text: String,
    /// Attachment descriptions; their content is not fetched for context.
    pub attachments: Vec<String>,
    /// The recorded protocol translation that produced this message.
    pub origin: MappingOrigin,
    /// Messages this earlier input quoted; attachments remain descriptions and no reads are made.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub quote: Option<EarlierQuote>,
}

impl EventBody {
    /// What this command acts on; an input, which is answered and drives a Run, has none.
    ///
    /// The match is exhaustive, so a new kind of Event must decide before it compiles.
    pub fn command_on(&self) -> Option<CommandOn> {
        match self {
            Self::Backtrack { .. } | Self::Halt(..) | Self::Compact => {
                Some(CommandOn::Conversation)
            }
            Self::SetProfile { .. } | Self::SetWorkingDir { .. } | Self::CancelSchedule { .. } => {
                Some(CommandOn::Session)
            }
            Self::PluginRolledBack { .. }
            | Self::UserMessage { .. }
            | Self::Reminder { .. }
            | Self::SessionMessage(..)
            | Self::ChildRunEnded { .. } => None,
        }
    }

    /// Whether this is a command, which is not answered, rather than an input.
    pub fn is_command(&self) -> bool {
        self.command_on().is_some()
    }

    /// The schedule this Event names, a reminder's or an owner's cancel's; the Inbox writes it
    /// only while that schedule is active.
    pub fn schedule(&self) -> Option<ScheduleId> {
        match self {
            Self::Reminder { schedule, .. } | Self::CancelSchedule { schedule } => Some(*schedule),
            Self::PluginRolledBack { .. }
            | Self::UserMessage { .. }
            | Self::Backtrack { .. }
            | Self::SessionMessage(..)
            | Self::ChildRunEnded { .. }
            | Self::Compact
            | Self::Halt(..)
            | Self::SetProfile { .. }
            | Self::SetWorkingDir { .. } => None,
        }
    }

    /// Whether this command stops the current Run and supersedes the inputs before it: a
    /// backtrack or a halt.
    ///
    /// The Run stops at its next boundary, and the superseded inputs are not answered.
    pub fn supersedes_inputs(&self) -> bool {
        matches!(self, Self::Backtrack { .. } | Self::Halt(..))
    }

    /// Whether this command leaves the inputs before it as they were: a compaction request or a
    /// command acting on the Session.
    ///
    /// It is consumed on its own: the model does not see it, it starts no Run, and a reply owed or
    /// awaited, a halt and the reply destination stand as they were.
    pub fn leaves_inputs(&self) -> bool {
        self.is_command() && !self.supersedes_inputs()
    }
}

impl Event {
    /// The recorded blobs this input refers to: its attachments, those of the messages it
    /// quotes, and the file of a Session message.
    pub fn blobs(&self) -> Vec<ContentHash> {
        match &self.body {
            EventBody::UserMessage {
                attachments, quote, ..
            } => quote
                .iter()
                .flat_map(Quote::attachments)
                .chain(attachments)
                .map(Attachment::content)
                .collect(),
            EventBody::SessionMessage(message) => {
                message.file.iter().map(|file| file.content).collect()
            }
            _ => Vec::new(),
        }
    }

    /// Whether this input's sender waits for a reply and moves the reply destination to itself.
    pub fn is_interactive(&self) -> bool {
        self.reply_destination().is_some()
    }

    /// The destination selected by this input, absent when it does not ask for a reply.
    pub fn reply_destination(&self) -> Option<ReplyDestination> {
        use EventBody::{
            Backtrack, CancelSchedule, ChildRunEnded, Compact, Halt, PluginRolledBack, Reminder,
            SessionMessage, SetProfile, SetWorkingDir, UserMessage,
        };
        use EventSource::{Channel, Child, Cli, Parent, Registry, Scheduler};
        match (&self.source, &self.body) {
            (Cli, UserMessage { .. } | Backtrack { .. }) => Some(ReplyDestination::Cli),
            (
                Channel {
                    protocol,
                    account,
                    conversation,
                    ..
                },
                UserMessage { .. } | Backtrack { .. },
            ) => Some(ReplyDestination::Channel {
                protocol: protocol.clone(),
                account: account.clone(),
                conversation: conversation.clone(),
            }),
            (Parent, SessionMessage(..)) => Some(ReplyDestination::Parent),
            (
                Cli | Channel { .. },
                PluginRolledBack { .. }
                | Reminder { .. }
                | SessionMessage(..)
                | ChildRunEnded { .. }
                | Halt(..)
                | Compact
                | SetProfile { .. }
                | SetWorkingDir { .. }
                | CancelSchedule { .. },
            )
            | (
                Parent,
                UserMessage { .. }
                | Backtrack { .. }
                | PluginRolledBack { .. }
                | Reminder { .. }
                | ChildRunEnded { .. }
                | Halt(..)
                | Compact
                | SetProfile { .. }
                | SetWorkingDir { .. }
                | CancelSchedule { .. },
            )
            | (
                Scheduler | Registry | Child(..),
                UserMessage { .. }
                | Backtrack { .. }
                | PluginRolledBack { .. }
                | Reminder { .. }
                | SessionMessage(..)
                | ChildRunEnded { .. }
                | Halt(..)
                | Compact
                | SetProfile { .. }
                | SetWorkingDir { .. }
                | CancelSchedule { .. },
            ) => None,
        }
    }

    /// The sole mapping from input to a model message: its own text, quoted pictures, then its own pictures.
    ///
    /// The composer narrates the circumstances, such as arrival and planned times. Input without
    /// text, such as a photo alone or a backtrack, has no text part.
    pub fn canonical_message(&self) -> Message {
        let (text, quote, attachments) = match &self.body {
            EventBody::UserMessage {
                text,
                quote,
                attachments,
                ..
            } => (text.as_str(), quote.as_ref(), attachments.as_slice()),
            EventBody::PluginRolledBack { text, .. } | EventBody::Reminder { text, .. } => {
                (text.as_str(), None, &[][..])
            }
            EventBody::SessionMessage(message) => (message.text.as_str(), None, &[][..]),
            EventBody::Backtrack { .. }
            | EventBody::ChildRunEnded { .. }
            | EventBody::Halt(..)
            | EventBody::Compact
            | EventBody::SetProfile { .. }
            | EventBody::SetWorkingDir { .. }
            | EventBody::CancelSchedule { .. } => ("", None, &[][..]),
        };
        let text = (!text.is_empty()).then(|| Part::Text { text: text.into() });
        Message {
            role: Role::User,
            parts: text
                .into_iter()
                .chain(
                    quote
                        .into_iter()
                        .flat_map(Quote::images)
                        .chain(attachments.iter().filter_map(Attachment::image))
                        .cloned()
                        .map(Part::Image),
                )
                .collect(),
        }
    }
}

