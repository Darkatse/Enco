use crate::{
    DateTime, EarlierQuote, EventId, Image, LogPos, MappingOrigin, Message, Part, Quote, Role,
    RolledBack, ScheduleId, SessionId, Unviewable, Utc,
};
use serde::{Deserialize, Serialize};

/// A deduplicated input delivered through the Inbox.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Event {
    /// Sender-assigned ID used to deduplicate repeated deliveries across restarts.
    pub id: EventId,
    /// Destination Session whose Inbox accepts this Event.
    pub session: SessionId,
    /// Producer used to distinguish interactive input from system notices.
    pub source: EventSource,
    /// Content that needs a Session Run.
    pub body: EventBody,
    /// Reception time for display, not Inbox ordering.
    pub received_at: DateTime<Utc>,
}

/// The producer of an Inbox input.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum EventSource {
    /// Input submitted through the native interface.
    Cli,
    /// Interactive input from a channel connection.
    Channel {
        /// Protocol declared by the channel mapper, such as `telegram`.
        protocol: String,
        /// Account identity within the protocol.
        account: String,
        /// Conversation to which default replies return.
        conversation: String,
        /// Authenticated sender within the protocol.
        sender: String,
        /// Display name reported when this input was accepted.
        sender_name: Option<String>,
        /// Whether the sender was the owner when this input was accepted.
        owner: bool,
        /// The recorded protocol translation that produced this input.
        origin: MappingOrigin,
        /// The protocol's ID for the message this input came from, by which the owner can point
        /// at it later.
        message: String,
    },
    /// Input generated by a durable schedule.
    Scheduler,
    /// Notice generated by automatic plugin recovery.
    Registry,
}

/// Input to a Session, consumed in Inbox order.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum EventBody {
    /// A failed trial generation and its committed replacement.
    GenerationRolledBack {
        /// Committed recovery facts.
        rollback: RolledBack,
        /// Notice written by the Registry when the rollback committed.
        text: String,
    },
    /// A message that drives this Session, with quoted context from its conversation.
    UserMessage {
        /// Text supplied by the sender.
        text: String,
        /// Images stored before this Event was accepted.
        images: Vec<Image>,
        /// Attachments whose content could not be accepted as images.
        unviewable: Vec<Unviewable>,
        /// Earlier messages quoted for context; excluded from the canonical message.
        earlier: Vec<EarlierMessage>,
        /// Messages this input replies to or forwards, with their stored images.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        quote: Option<Quote>,
    },
    /// A reminder reaching its scheduled time.
    Reminder {
        /// The Schedule which produced this input.
        schedule: ScheduleId,
        /// Planned time in UTC; this occurrence's identity together with the schedule.
        due_at: DateTime<Utc>,
        /// Earlier missed occurrences omitted when delivering only the latest one.
        skipped: u32,
        /// Reminder text copied from its Schedule.
        text: String,
    },
    /// The owner took the conversation back to a recorded position and continues from there.
    ///
    /// It carries no text: the composer narrates it. Changes made after the position outside the
    /// conversation stay as they are.
    Backtrack {
        /// The position the owner pointed at; the kernel derives what the conversation keeps.
        to: LogPos,
    },
}

/// A prior chat message quoted as context, without starting a Session Run.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EarlierMessage {
    /// Reception time for display, not ordering.
    pub received_at: DateTime<Utc>,
    /// Protocol sender ID, when reported.
    pub sender: Option<String>,
    /// Display name reported when this message arrived.
    pub sender_name: Option<String>,
    /// Whether the sender was the owner when this message arrived.
    pub owner: bool,
    /// Quoted text, never an instruction from the owner on another sender's behalf.
    pub text: String,
    /// Attachment descriptions; their content is not fetched for context.
    pub attachments: Vec<String>,
    /// The recorded protocol translation that produced this message.
    pub origin: MappingOrigin,
    /// Messages this earlier input quoted; images remain descriptions and no reads are made.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub quote: Option<EarlierQuote>,
}

impl Event {
    /// The sole mapping from input to a model message: its own text, quoted pictures, then its own pictures.
    ///
    /// The composer narrates the circumstances, such as arrival and planned times. Input without
    /// text, such as a photo alone or a backtrack, has no text part.
    pub fn canonical_message(&self) -> Message {
        let (text, quote, images) = match &self.body {
            EventBody::UserMessage {
                text,
                quote,
                images,
                ..
            } => (text.as_str(), quote.as_ref(), images.as_slice()),
            EventBody::GenerationRolledBack { text, .. } | EventBody::Reminder { text, .. } => {
                (text.as_str(), None, &[][..])
            }
            EventBody::Backtrack { .. } => ("", None, &[][..]),
        };
        let text = (!text.is_empty()).then(|| Part::Text { text: text.into() });
        Message {
            role: Role::User,
            parts: text
                .into_iter()
                .chain(
                    quote
                        .into_iter()
                        .flat_map(Quote::images)
                        .chain(images)
                        .cloned()
                        .map(Part::Image),
                )
                .collect(),
        }
    }
}
